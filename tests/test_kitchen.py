import os
import shutil
import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

KITCHEN = Path(__file__).resolve().parent.parent / "bin" / "kitchen"

VALID_SKILL = textwrap.dedent("""\
    ---
    name: {name}
    description: "Do one thing well. Use when the fixture needs a valid skill."
    ---

    # {name}

    See [the reference](reference.md).
    """)


class KitchenFixture(unittest.TestCase):
    """A throwaway repo and HOME, so tests never touch the real setup."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        self.repo = root / "repo"
        self.home = root / "home"
        (self.repo / "skills").mkdir(parents=True)
        (self.repo / "bin").mkdir()
        shutil.copy(KITCHEN, self.repo / "bin" / "kitchen")
        shutil.copytree(KITCHEN.parent.parent / "lib", self.repo / "lib", ignore=shutil.ignore_patterns("__pycache__"))
        self.home.mkdir()
        subprocess.run(["git", "init", "-q", str(self.repo)], check=True)

    extra_env = {}

    def tearDown(self):
        self.tmp.cleanup()

    def add_skill(self, name, text=None, files=("reference.md",)):
        skill = self.repo / "skills" / name
        skill.mkdir(parents=True)
        (skill / "SKILL.md").write_text(text if text is not None else VALID_SKILL.format(name=name))
        for file in files:
            (skill / file).write_text("detail\n")
        return skill

    def write_generated_rules(self, path):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("<!-- Generated by `kitchen install` from somewhere. -->\n\n# Old rules\n")

    def kitchen_env(self, denylist=None, env_extra=None):
        env = {**os.environ, "HOME": str(self.home), "KITCHEN_REPO": str(self.repo), **(env_extra or {})}
        env["KITCHEN_DENYLIST"] = str(denylist or self.home / "no-denylist.txt")
        env["KITCHEN_STATE"] = str(self.home / "state")
        env["KITCHEN_CONFIG"] = str(self.home / "config")
        env.update(self.extra_env)
        return env

    def kitchen(self, *args, denylist=None, cwd=None, env_extra=None):
        return subprocess.run([sys.executable, str(KITCHEN), *args], env=self.kitchen_env(denylist, env_extra),
                              capture_output=True, text=True, cwd=cwd)


class InstallTests(KitchenFixture):
    def test_install_links_each_skill_into_claude_and_codex(self):
        skill = self.add_skill("alpha")

        result = self.kitchen("install")

        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        for target in (self.home / ".claude" / "skills" / "alpha", self.home / ".agents" / "skills" / "alpha"):
            self.assertTrue(target.is_symlink())
            self.assertEqual(target.resolve(), skill.resolve())

    def test_install_removes_the_chef_agent_an_older_install_linked_and_keeps_the_persons_own(self):
        old = self.repo.resolve() / "agents"  # where an older kitchen kept it (install linked resolved paths); gone now
        old.mkdir()
        (old / "chef.md").write_text("---\nname: chef\n---\n")
        (old / "chef.toml").write_text('name = "chef"\n')
        claude, codex = self.home / ".claude" / "agents", self.home / ".codex" / "agents"
        for folder, name in ((claude, "chef.md"), (codex, "chef.toml")):
            folder.mkdir(parents=True)
            (folder / name).symlink_to(old / name)
        (claude / "mine.md").write_text("---\nname: mine\n---\n")
        for name in ("chef.md", "chef.toml"):
            (old / name).unlink()
        old.rmdir()

        result = self.kitchen("install")

        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(sorted(p.name for p in claude.iterdir()), ["mine.md"])
        self.assertEqual(list(codex.iterdir()), [])

    def test_install_registers_no_agent_even_when_the_repo_has_a_definition(self):
        # Claude Code may delegate to any registered agent on its own; chef mode must start only when the owner asks
        (self.repo / "agents").mkdir()
        (self.repo / "agents" / "chef.md").write_text("---\nname: chef\n---\n")
        (self.repo / "agents" / "chef.toml").write_text('name = "chef"\n')

        result = self.kitchen("install")

        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse((self.home / ".claude" / "agents").exists())
        self.assertFalse((self.home / ".codex" / "agents").exists())

    def test_install_writes_no_global_rules(self):
        (self.repo / "PRINCIPLES.md").write_text("# Principles\n\n## 1. Prove it on the real thing (`prove`)\n\nDone means you saw it.\n")
        (self.repo / "global").mkdir()
        (self.repo / "global" / "AGENTS.md").write_text("# Rules\n")  # what an older install would have written out

        result = self.kitchen("install")

        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse((self.home / ".claude" / "CLAUDE.md").exists())
        self.assertFalse((self.home / ".codex" / "AGENTS.md").exists())

    def test_install_moves_a_rules_file_an_older_install_wrote_aside_and_keeps_the_persons_own(self):
        old = self.home / ".claude" / "CLAUDE.md"
        self.write_generated_rules(old)
        mine = self.home / ".codex" / "AGENTS.md"
        mine.parent.mkdir(parents=True)
        mine.write_text("# My own rules\n")

        result = self.kitchen("install")

        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse(old.exists())
        backups = list((self.home / ".kitchen-backups").rglob("CLAUDE.md"))
        self.assertEqual([b.read_text().splitlines()[-1] for b in backups], ["# Old rules"])
        self.assertIn("the kitchen no longer writes your agent rules", result.stdout)
        self.assertEqual(mine.read_text(), "# My own rules\n")

    def test_install_moves_the_old_link_to_global_rules_aside(self):
        (self.repo / "global").mkdir()
        rules = self.repo / "global" / "AGENTS.md"
        rules.write_text("# Rules\n")
        old = self.home / ".claude" / "CLAUDE.md"
        old.parent.mkdir(parents=True)
        old.symlink_to(rules.resolve())  # the oldest install linked the resolved path

        result = self.kitchen("install")

        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse(old.is_symlink() or old.exists())
        self.assertEqual(rules.read_text(), "# Rules\n")

    def test_install_moves_rules_linked_from_another_clone_aside(self):
        other = Path(self.tmp.name) / "old-clone"
        (other / "global").mkdir(parents=True)
        (other / "bin").mkdir()
        (other / "bin" / "kitchen").write_text("#!/bin/sh\n")
        (other / "global" / "AGENTS.md").write_text("# Rules\n")
